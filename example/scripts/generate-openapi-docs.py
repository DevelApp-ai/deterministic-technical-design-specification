#!/usr/bin/env python3
"""Render the build-time OpenAPI document into a MkDocs page.

Reads ``docs/generated/openapi.json`` — the OpenAPI document that
``dotnet build`` emits natively via ``Microsoft.AspNetCore.OpenApi``
(build-time generation, no Swashbuckle reflection) — and renders a
human-readable API reference page at ``docs/application/api-reference.md``.

Deterministic: output depends only on the input document. No timestamps,
no environment data, document order preserved. Standard library only.

Usage (from the ``example/`` directory or anywhere)::

    python3 scripts/generate-openapi-docs.py
"""

from __future__ import annotations

import json
import re
from pathlib import Path

EXAMPLE_ROOT = Path(__file__).resolve().parent.parent
OPENAPI_DOCUMENT = EXAMPLE_ROOT / "docs" / "generated" / "openapi.json"
OUTPUT_PAGE = EXAMPLE_ROOT / "docs" / "application" / "api-reference.md"

# The pipeline treats OpenAPI 3.1 as the contract version; the renderer
# fails loudly if the emitted document drifts to another major.minor.
SUPPORTED_OPENAPI = "3.1"


def load_document() -> dict:
    if not OPENAPI_DOCUMENT.exists():
        raise SystemExit(
            "error: " + str(OPENAPI_DOCUMENT.relative_to(EXAMPLE_ROOT))
            + " not found — run `dotnet build example/dotnet/MyApp.slnx` first"
            + " (build-time OpenAPI generation is enabled on MyApp.Api)."
        )
    document = json.loads(OPENAPI_DOCUMENT.read_text(encoding="utf-8"))
    version = document.get("openapi", "")
    if not version.startswith(SUPPORTED_OPENAPI):
        raise SystemExit(
            f"error: expected OpenAPI {SUPPORTED_OPENAPI}.x, got '{version}'"
            " — update this renderer before shipping the new format."
        )
    return document


def anchor(name: str) -> str:
    """MkDocs heading anchor: lower-case, spaces and dots collapse."""
    return re.sub(r"[^\w\- ]", "", name.lower()).replace(" ", "-")


def schema_link(schema: dict) -> str:
    """Render a schema node as Markdown, linking to the schema appendix."""
    if not isinstance(schema, dict):
        return "`unknown`"
    if "$ref" in schema:
        name = schema["$ref"].rsplit("/", 1)[-1]
        return f"[{name}](#{anchor(name)})"
    schema_type = schema.get("type")
    if isinstance(schema_type, list):
        # OpenAPI 3.1 union types, e.g. ["null", "string"] — render sorted
        # so the output stays deterministic and table-cell safe.
        union = "/".join(f"`{t}`" for t in sorted(schema_type))
        return f"{union} (nullable)" if "null" in schema_type and len(schema_type) > 1 else union
    if schema_type == "array":
        return f"array of {schema_link(schema.get('items', {}))}"
    if schema_type:
        return f"`{schema_type}`"
    return "`object`"


def cell(value: str) -> str:
    """Escape pipes so values never break their Markdown table row."""
    return value.replace("|", "\\|")


def render_metadata(document: dict) -> list[str]:
    info = document.get("info", {})
    openapi_version = document.get("openapi", "")
    return [
        "# .NET API Reference (OpenAPI)",
        "",
        '!!! note "Auto-generated"',
        "    This page is rendered from `docs/generated/openapi.json` — the",
        f"    OpenAPI **{openapi_version}** document that `dotnet build` emits",
        "    at build time from the MyApp.Api controllers via native",
        "    `Microsoft.AspNetCore.OpenApi` generation (no Swashbuckle",
        "    reflection). Re-render with `python3 scripts/generate-openapi-docs.py`",
        "    after rebuilding the solution.",
        "",
        "| Field | Value |",
        "|-------|-------|",
        f"| **OpenAPI version** | `{openapi_version}` |",
        f"| **Document version** | `{info.get('version', '')}` |",
        f"| **Title** | `{cell(info.get('title', ''))}` |",
        "| **Generated by** | native build-time OpenAPI generation (`dotnet build`) |",
        "| **Raw document** | [openapi.json](../generated/openapi.json) |",
        "| **Related Requirements** | [MoSCoW Prioritisation](../requirements/moscow.md) |",
        "",
        "## Endpoint Inventory",
        "",
        "| Method | Route | Summary |",
        "|--------|-------|---------|",
    ]


def render_operations(document: dict) -> list[str]:
    lines: list[str] = []
    for path, path_item in document.get("paths", {}).items():
        for method, operation in path_item.items():
            summary = operation.get("summary") or operation.get("description") or ""
            lines.append(
                f"| {method.upper()} | `{path}` | {summary} |"
            )
    lines.extend(["", "## Endpoints", ""])

    for path, path_item in document.get("paths", {}).items():
        for method, operation in path_item.items():
            summary = operation.get("summary") or ""
            lines.append(f"### {method.upper()} {path}")
            lines.append("")
            if summary:
                lines.append(summary)
                lines.append("")

            parameters = operation.get("parameters") or []
            if parameters:
                lines.append("**Parameters:**")
                lines.append("")
                lines.append("| Name | In | Type | Required | Description |")
                lines.append("|------|----|------|----------|-------------|")
                for parameter in parameters:
                    description = parameter.get("description") or ""
                    lines.append(
                        f"| `{parameter['name']}` | {parameter.get('in', '')}"
                        f" | {schema_link(parameter.get('schema', {}))}"
                        f" | {parameter.get('required', False)} | {cell(description)} |"
                    )
                lines.append("")

            request_body = operation.get("requestBody")
            if request_body:
                content = request_body.get("content", {}).get("application/json")
                if content:
                    lines.append(
                        "**Request body** (`application/json`): "
                        + schema_link(content.get("schema", {}))
                    )
                    lines.append("")

            responses = operation.get("responses") or {}
            if responses:
                lines.append("**Responses:**")
                lines.append("")
                lines.append("| Status | Description | Schema |")
                lines.append("|--------|-------------|--------|")
                for status, response in responses.items():
                    description = response.get("description") or ""
                    content = (response.get("content") or {}).get("application/json")
                    schema = schema_link(content.get("schema", {})) if content else "—"
                    lines.append(f"| {status} | {description} | {schema} |")
                lines.append("")

    return lines


def render_schemas(document: dict) -> list[str]:
    schemas = (document.get("components") or {}).get("schemas") or {}
    if not schemas:
        return []

    lines = ["## Schemas", ""]
    for name, schema in schemas.items():
        description = (schema.get("description") or "").strip()
        lines.append(f"### {name}")
        lines.append("")
        if description:
            lines.append(description)
            lines.append("")

        properties = schema.get("properties") or {}
        if properties:
            required = set(schema.get("required") or [])
            lines.append("| Property | Type | Required | Description |")
            lines.append("|----------|------|----------|-------------|")
            for prop_name, prop_schema in properties.items():
                prop_description = (prop_schema.get("description") or "").strip()
                lines.append(
                    f"| `{prop_name}` | {schema_link(prop_schema)}"
                    f" | {prop_name in required} | {cell(prop_description)} |"
                )
            lines.append("")

    return lines


def render_traceability() -> list[str]:
    return [
        "## Traceability",
        "",
        "The OpenAPI document is a traceable pipeline artefact: it is generated",
        "deterministically at build time, rendered into this page, and linked",
        "into the traceability matrix. See the",
        "[Traceability Matrix](../traceability/index.md) for the full chain",
        "from MoSCoW requirements to ADRs, policies, and code.",
        "",
        "The native `Microsoft.AspNetCore.OpenApi` build-time generation",
        "approach (over Swashbuckle) will be recorded in an upcoming ADR as",
        "part of the .NET ADR series.",
        "",
    ]


def main() -> None:
    document = load_document()
    lines = [
        *render_metadata(document),
        *render_operations(document),
        *render_schemas(document),
        *render_traceability(),
    ]
    OUTPUT_PAGE.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_PAGE.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")
    print(f"generated {OUTPUT_PAGE.relative_to(EXAMPLE_ROOT)}")


if __name__ == "__main__":
    main()
